/** Strict getter: returns translated string or a safe placeholder. */
export function t(language, key, params) {
  const lang = isValidClientLanguage(language) ? language : CLIENT_LANGUAGE_DEFAULT;
  const dict = DICTIONARY[lang];
  const template = dict?.[key];
  if (typeof template !== "string") {
    const isDevOrTest =
      (typeof process !== "undefined" && process.env && (process.env.NODE_ENV === "test" || process.env.CI)) ||
      (typeof import.meta !== "undefined" && import.meta.env && import.meta.env.MODE === "test");
    if (isDevOrTest) {
      throw new Error(`Missing i18n key: ${key} for language ${lang}`);
    }
    return `[${key}]`;
  }
  return interpolate(template, params);
}

export function tStatus(language, statusId) {
  return t(language, `client.status.${statusId}`) || t(language, "client.status.not_bought");
}

const STANDARD_UNIT_MAP = Object.freeze({
  "шт.": "client.unit.pcs",
  шт: "client.unit.pcs",
  м: "client.unit.m",
  "м²": "client.unit.m2",
  "м³": "client.unit.m3",
  кг: "client.unit.kg",
  г: "client.unit.g",
  л: "client.unit.l",
  комплект: "client.unit.set",
  услуга: "client.unit.service",
});

export function tUnit(language, rawUnit) {
  if (rawUnit == null || rawUnit === "") return "";
  const key = STANDARD_UNIT_MAP[String(rawUnit).trim().toLowerCase()];
  if (!key) return String(rawUnit);
  return t(language, key);
}

export function tError(language, code) {
  const key = `client.error.${code}`;
  const title = t(language, `${key}.title`);
  if (title === `[${key}.title]`) {
    return {
      title: t(language, "client.error.unknown.title"),
      hint: t(language, "client.error.unknown.hint"),
    };
  }
  return { title, hint: t(language, `${key}.hint`) };
}

export function clientProjectLoadMessageI18n(language, kind) {
  switch (kind) {
    case "NOT_PUBLISHED":
      return {
        title: t(language, "client.loadError.notPublished.title"),
        hint: t(language, "client.loadError.notPublished.hint"),
      };
    case "EXPIRED":
      return {
        title: t(language, "client.loadError.expired.title"),
        hint: t(language, "client.loadError.expired.hint"),
      };
    case "NOT_FOUND":
      return {
        title: t(language, "client.loadError.notFound.title"),
        hint: t(language, "client.loadError.notFound.hint"),
      };
    default:
      return {
        title: t(language, "client.loadError.network.title"),
        hint: t(language, "client.loadError.network.hint"),
      };
  }
}
