/** Lightweight shared i18n for the client-facing surface (UI, PDF, Excel).
 *  Semantic keys only — never use a Russian phrase as a key.
 *  Fallback language is "ru". Unknown keys return a safe placeholder.
 */

export const CLIENT_LANGUAGE_DEFAULT = "ru";
export const CLIENT_LANGUAGES = Object.freeze([
  { code: "ru", label: "Русский" },
  { code: "en", label: "English" },
]);

const ALLOWED_LANGUAGES = new Set(["ru", "en"]);

export function isValidClientLanguage(value) {
  return ALLOWED_LANGUAGES.has(String(value || "").trim().toLowerCase());
}

export function normalizeClientLanguage(value) {
  const raw = String(value || "").trim().toLowerCase();
  return ALLOWED_LANGUAGES.has(raw) ? raw : CLIENT_LANGUAGE_DEFAULT;
}

/** Simple positional / named interpolation. */
function interpolate(template, params) {
  if (params == null) return template;
  if (Array.isArray(params)) {
    let i = 0;
    return String(template).replace(/\{(\w+)\}/g, () => {
      const val = params[i];
      i += 1;
      return val != null ? String(val) : "";
    });
  }
  return String(template).replace(/\{(\w+)\}/g, (_m, key) => {
    const val = params[key];
    return val != null ? String(val) : "";
  });
}

